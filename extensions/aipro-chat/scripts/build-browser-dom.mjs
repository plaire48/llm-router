import {build} from 'esbuild';
import {mkdir, readFile, writeFile} from 'node:fs/promises';
import {PAGE_BUILTINS} from './page-builtins.mjs';

// Chrome/Playwright serialize injected functions without their module closure.
// Embed the pinned library INSIDE each static function, at build time only.
const result = await build({entryPoints: ['browser-dom.js'], bundle: true, write: false, platform: 'browser', format: 'iife', globalName: 'NubiDOM', target: 'chrome125', minify: true, legalComments: 'inline'});
const bundle = result.outputFiles[0].text;
await mkdir('generated', {recursive: true});
const deck = await readFile('design/agent-deck.css', 'utf8');
const pointerTheme = Object.fromEntries(Object.entries({ink: 'bird-ink', cursorInk: 'deck-ink', aqua: 'bird-aqua', blue: 'deck-blue', soft: 'deck-blue-soft', surface: 'deck-card'}).map(([key, token]) => {
  const value = deck.match(new RegExp(`--${token}:\\s*(#[A-Fa-f0-9]{6});`))?.[1];
  if (!value) throw new Error(`Missing pointer theme token: ${token}`);
  return [key, value];
}));
for (const [key, token] of Object.entries({travel: 'deck-pointer-travel', pulse: 'deck-pointer-pulse', feedback: 'deck-feedback'})) {
  const value = deck.match(new RegExp(`--${token}:\\s*(\\d+)ms;`))?.[1];
  if (!value) throw new Error(`Missing pointer motion token: ${token}`);
  pointerTheme[key] = Number(value);
}
pointerTheme.ease = deck.match(/--deck-ease:\s*(cubic-bezier\([\d.,\s]+\));/)?.[1];
if (!pointerTheme.ease) throw new Error('Missing pointer motion token: deck-ease');
await writeFile('generated/browser-pointer-theme.js', `// Generated from design/agent-deck.css. Do not edit.\nexport const POINTER_THEME = ${JSON.stringify(pointerTheme)};\n`);
await writeFile('generated/browser-dom.js', `// Generated by scripts/build-browser-dom.mjs. Do not edit.\n` + ['collectSnapshot', 'inspectTarget', 'clickTarget', 'controlState', 'valueMark', 'pointerPosition', 'pointerCover', 'pointerBlocker', 'fieldMarks', 'prepareHoverReveal', 'waitForHoverReveal', 'stateWords'].map(name => `export function ${name}(input, extra) {\n${PAGE_BUILTINS}\n${bundle}\nreturn NubiDOM.${name}(input, extra);\n}\n`).join(''));
const content = await build({entryPoints: ['browser-content-dom.js'], bundle: true, write: false, platform: 'browser', format: 'iife', globalName: 'NubiContent', target: 'chrome125', minify: true, legalComments: 'inline'});
await writeFile('generated/browser-content-dom.js', `// Generated static content reader. Do not edit.\nexport function collectPageContent() {\n${content.outputFiles[0].text}\nreturn NubiContent.collectPageContent();\n}\n`);
