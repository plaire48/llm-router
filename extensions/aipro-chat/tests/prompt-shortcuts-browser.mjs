import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import {mkdtemp, cp, rm, mkdir} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {resolve} from 'node:path';

const profile = await mkdtemp(resolve(tmpdir(), 'nubi-prompt-shortcuts-'));
const extension = resolve(profile, 'extension');
const shots = resolve('verification', 'prompt-shortcuts');
const errors = [];
const token = `header.${Buffer.from(JSON.stringify({exp:Math.floor(Date.now()/1000)+3600})).toString('base64url')}.signature`;
let context;
try {
  await cp(resolve('dist'), extension, {recursive:true});
  await mkdir(shots, {recursive:true});
  context = await chromium.launchPersistentContext(profile, {headless:true, channel:'chromium', executablePath:process.env.CHROME_BINARY || undefined,
    args:[`--disable-extensions-except=${extension}`, `--load-extension=${extension}`]});
  await context.route('https://aipro.sdsdev.co.kr/**', async route => {
    if (new URL(route.request().url()).pathname === '/api/models') return route.fulfill({json:{modelList:[{name:'GLM-5.2-NVFP4',display_name:'GLM-5.2',target:'chat',context_length:100000,max_input_tokens:80000}]}});
    throw new Error('A saved prompt was sent without the user sending it');
  });
  const worker = context.serviceWorkers()[0] || await context.waitForEvent('serviceworker');
  await worker.evaluate(async credential => chrome.storage.session.set({credential}), {mode:'browser',token,receivedAt:7});
  const ui = await context.newPage();
  ui.on('pageerror', error => errors.push(error.message));
  await ui.setViewportSize({width:360,height:800});
  await ui.goto(`chrome-extension://${new URL(worker.url()).hostname}/index.html`);
  assert.equal(await ui.evaluate(() => typeof navigator.locks?.request), 'function');
  const composer = ui.getByRole('textbox', {name:'메시지', exact:true});
  await composer.waitFor();
  await ui.getByRole('button', {name:'설정', exact:true}).click();
  const dialog = ui.getByRole('dialog', {name:'설정', exact:true});
  await dialog.getByText('프롬프트 바로가기', {exact:true}).click();
  await dialog.getByRole('button', {name:'바로가기 추가'}).click();
  const form = dialog.getByRole('form', {name:'프롬프트 바로가기 추가'});
  assert.equal(await form.getByRole('textbox', {name:'이름'}).evaluate(element => document.activeElement === element), true);
  await form.getByRole('textbox', {name:'이름'}).fill('보고서 검토');
  await form.getByRole('textbox', {name:'프롬프트'}).fill('보고서의 누락 항목을 세 가지로 정리해 줘.');
  await form.getByRole('button', {name:'저장'}).click();
  await dialog.getByText('/p:보고서-검토').waitFor();
  await ui.screenshot({path:resolve(shots,'settings-360.png')});
  assert.equal(await ui.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await dialog.getByRole('button', {name:'보고서 검토 예약'}).click();
  const reservation = dialog.getByRole('form', {name:'작업 예약'});
  await reservation.getByRole('textbox', {name:'예약 이름'}).waitFor({state:'visible'});
  await ui.waitForFunction(() => document.querySelector('form[aria-label="작업 예약"] input[name="name"]')?.value === '보고서 검토');
  assert.equal(await reservation.getByRole('textbox', {name:'예약 이름'}).inputValue(), '보고서 검토');
  assert.equal(await reservation.getByRole('textbox', {name:'실행할 요청'}).inputValue(), '보고서의 누락 항목을 세 가지로 정리해 줘.');
  assert.equal(await reservation.getByRole('textbox', {name:'시작 페이지'}).inputValue(), '');
  assert.equal(await reservation.getByRole('textbox', {name:'시작 페이지'}).evaluate(element => document.activeElement === element), true);
  assert.equal((await worker.evaluate(() => chrome.storage.local.get('browserRoutines'))).browserRoutines?.jobs?.length || 0, 0);
  await ui.screenshot({path:resolve(shots,'schedule-from-shortcut-360.png')});
  assert.equal(await ui.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  console.log('PASS a saved prompt opens an editable reservation without running or scheduling it');
  await ui.setViewportSize({width:1000,height:800});
  await ui.screenshot({path:resolve(shots,'settings-1000.png')});
  await ui.keyboard.press('Escape');
  await composer.fill('/p:');
  const menu = ui.locator('#skill-command-menu');
  await menu.getByRole('button', {name:/보고서 검토/}).click();
  assert.equal(await composer.inputValue(), '보고서의 누락 항목을 세 가지로 정리해 줘.');
  assert.equal(await ui.getByRole('article').count(), 0);
  await ui.waitForFunction(async expected => (await chrome.runtime.sendMessage({type:'GET_STATE'})).data.chat.draft === expected, '보고서의 누락 항목을 세 가지로 정리해 줘.');
  console.log('PASS choosing a saved prompt only fills the composer');
  await ui.reload();
  await composer.waitFor();
  assert.equal(await composer.inputValue(), '보고서의 누락 항목을 세 가지로 정리해 줘.');
  await composer.fill('/p:보고서-검토');
  await ui.getByRole('button', {name:'전송', exact:true}).click();
  assert.equal(await composer.inputValue(), '보고서의 누락 항목을 세 가지로 정리해 줘.');
  assert.equal(await ui.getByRole('article').count(), 0);
  await composer.fill('/wiki');
  await composer.press('Enter');
  assert.equal(await composer.inputValue(), '/wiki ');
  console.log('PASS existing skill slash commands still prefill');
  await ui.getByRole('button', {name:'설정', exact:true}).click();
  assert.equal(await dialog.locator('form[aria-label="작업 예약"] input[name="name"]').inputValue(), '');
  await dialog.getByText('프롬프트 바로가기', {exact:true}).click();
  await dialog.getByRole('button', {name:'보고서 검토 편집'}).click();
  const edit = dialog.getByRole('form', {name:'프롬프트 바로가기 편집'});
  await edit.getByRole('textbox', {name:'프롬프트'}).fill('새 프롬프트');
  await edit.getByRole('button', {name:'저장'}).click();
  await edit.waitFor({state:'detached'});
  await dialog.getByText('새 프롬프트', {exact:true}).waitFor();
  await dialog.getByRole('button', {name:'보고서 검토 삭제'}).click();
  await dialog.getByRole('button', {name:'삭제 확인'}).click();
  await dialog.getByText('/p:보고서-검토').waitFor({state:'detached'});
  await ui.keyboard.press('Escape');
  await composer.fill('/p:');
  assert.equal(await ui.locator('#skill-command-menu').count(), 0);
  assert.deepEqual(errors, []);
  console.log('PASS edit, delete, reload persistence, narrow and wide layouts');
} finally {
  await context?.close();
  await rm(profile,{recursive:true,force:true});
}
