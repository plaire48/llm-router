export const naverTasks=scenarios.flatMap((scenario,scenarioIndex)=>scenario.tasks.map(([goal,outcomeEvidence],taskIndex)=>({
  id:`naver-${String(scenarioIndex+1).padStart(2,'0')}-${String(taskIndex+1).padStart(2,'0')}`,
  domain:scenario.domain,
  site:'naver',
  startUrl:`https://search.naver.com/search.naver?query=${encodeURIComponent(scenario.query)}`,
  goal,
  outcomeEvidence,
  readOnly:true,
})));

if(naverTasks.length!==50||new Set(naverTasks.map(task=>task.id)).size!==50)throw new Error('naver_task_catalog_invalid');
